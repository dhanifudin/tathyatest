import { readFileSync } from 'node:fs';
import type { TathyaConfig } from '../config.js';

/** Published path (inside `output.dir`) of the shared support module every spec imports. */
export const SUPPORT_MODULE_PATH = 'support/tathya.ts';

/** Import specifier for the support module from a spec in a category folder (`<dir>/<file>`). */
export const SUPPORT_IMPORT = '../support/tathya.js';

export const GENERATED_HEADER = '// Generated by `tt generate` — do not edit; this file is overwritten on every run.\n';

/**
 * Source of `support/tathya.ts`: the one place the generated suite keeps its login helpers,
 * fixtures, and oracle helpers. Specs stay short and read as scenarios; everything app-specific
 * (credentials, login path, error indicator, reset hook) is pinned here from the config.
 */
export function supportModuleSource(config: Pick<TathyaConfig, 'auth' | 'oracle' | 'hooks'>): string {
  const credentials = Object.fromEntries(config.auth.roles.map((role) => [role.name, { username: role.username, password: role.password }]));
  const reset = config.hooks?.reset ?? null;
  const pinned = [
    '/** Credentials per role, from tathya.config.yaml. */',
    `export const roleCredentials = ${JSON.stringify(credentials, null, 2)} as const;`,
    'export type Role = keyof typeof roleCredentials;',
    '',
    `const loginPath = ${JSON.stringify(config.auth.loginPath)};`,
    `const errorSelector = ${JSON.stringify(config.oracle.errorSelector)};`,
    `const resetHook: { method: 'POST' | 'GET' | 'DELETE'; path: string } | null = ${JSON.stringify(reset)};`,
    '',
  ].join('\n');
  // Drop the template's explanatory header (everything before the first import), then pin the config.
  const template = loadTemplate();
  return GENERATED_HEADER + template.slice(template.indexOf('import ')).replace(CONFIG_BLOCK, () => pinned);
}

/** The block of the template that `supportModuleSource` replaces with values from the user's config. */
const CONFIG_BLOCK = /\/\/ <tathya:config>\n[\s\S]*?\/\/ <\/tathya:config>\n/;

let templateCache: string | undefined;
function loadTemplate(): string {
  templateCache ??= readFileSync(new URL('./templates/support.ts', import.meta.url), 'utf8');
  return templateCache;
}
